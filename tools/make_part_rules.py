#!/usr/bin/env python3
"""Compiles the art records' part rules into game/data/creature/part_rules.json.

assets/records/ carries a .gdignore, so Godot never exports it: a player's Pangaea.exe has no
cpart_*.json, and the creature editor's palette, the save validation and the rivals' parts all
read the part rules at run time. This script copies each record's "part_rules" (keyed by type, in
type order) into one data file the pack does carry. Run it after tools/blender/make_creature_parts.py;
tests/test_assets.gd fails while the file and the records disagree.

Usage: python tools/make_part_rules.py [--check]   (--check: exit 1 when the file is stale, write nothing)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RECORDS = ROOT / "assets" / "records"
OUT = ROOT / "game" / "data" / "creature" / "part_rules.json"


def compile_rules() -> dict:
    rules = {}
    for record_path in sorted(RECORDS.glob("cpart_*.json")):
        record = json.loads(record_path.read_text(encoding="utf-8"))
        part_rules = record.get("part_rules")
        if part_rules:
            rules[part_rules["type"]] = part_rules
    return {
        "_comment": "Generated by tools/make_part_rules.py from assets/records/cpart_*.json; do not edit by hand.",
        "source": "assets/records/cpart_*.json",
        "rules": dict(sorted(rules.items())),
    }


def main() -> int:
    text = json.dumps(compile_rules(), indent="\t", ensure_ascii=False) + "\n"
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run python tools/make_part_rules.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} matches the records")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(json.loads(text)['rules'])} part types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
